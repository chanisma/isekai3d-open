export type IconName = keyof typeof ICONS;

/** A gold line icon, sized to the text around it. `filled` fills it (a starred job). */
export function Icon({ name, filled, className }: { name: IconName; filled?: boolean; className?: string }) {
  const Glyph = ICONS[name];
  return <Glyph className={`ui-icon ${filled ? 'filled' : ''} ${className ?? ''}`} aria-hidden strokeWidth={1.9} absoluteStrokeWidth={false} />;
}
