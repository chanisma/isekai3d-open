export function skillGuide(k: SkillKey): SkillGuide | null {
  const e = GUIDE[k];
  const what = e?.what ?? SKILL_WHY[k];
  return e && what ? { what, life: e.life, real: e.real } : null;
}

/**
 * How to grow it in the game, as a list, and what it's good for once grown (the part of SKILL_HOWTO
 * after «쓸모:»). Commas inside brackets stay with their item.
 */
export function gameWays(k: SkillKey): { ways: string[]; use?: string } {
  const text = SKILL_HOWTO[k] ?? YOUNG_HOWTO[k] ?? '';
  const [how, use] = text.split(' · 쓸모: ');
  const ways: string[] = [];
  let depth = 0;
  let cur = '';
  for (const ch of how) {
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (ch === ',' && depth === 0) {
      ways.push(cur.trim());
      cur = '';
    } else cur += ch;
  }
  if (cur.trim()) ways.push(cur.trim());
  return { ways, ...(use ? { use } : {}) };
}

export type SkillRole = 'main' | 'base' | 'branch' | 'top';
export const ROLE_LABEL: Record<SkillRole, string> = { main: '대표 역량', base: '기반 역량', branch: '갈래 역량', top: '상위 단계' };

/** Jobs that ask for a skill, and how (대표 first). */
export function jobsNeeding(k: SkillKey): Array<{ career: Career; role: SkillRole }> {
  const out: Array<{ career: Career; role: SkillRole }> = [];
  for (const c of CAREERS) {
    const p = SKILL_PROFILES[c.id];
    if (!p || c.school || c.partTime) continue;
    const role: SkillRole | null = p.main === k ? 'main' : p.base === k ? 'base' : p.branches.some((b) => b.skill === k) ? 'branch' : p.branches.some((b) => b.top === k) ? 'top' : null;
    if (role) out.push({ career: c, role });
  }
  const order: SkillRole[] = ['main', 'base', 'branch', 'top'];
  return out.sort((a, b) => order.indexOf(a.role) - order.indexOf(b.role));
}

/** The groups the guide lists for a dweller of this age: grown-up groups, or a young dweller's own skills first. */
export function guideGroups(age: string): Array<{ label: string; keys: SkillKey[] }> {
  if (age === 'toddler') return [{ label: '유아 역량', keys: [...TODDLER_SKILLS] }];
  const grown = SKILL_GROUPS.map((x) => ({ ...x, keys: x.keys.filter((k) => GUIDE[k]) }));
  if (age === 'child') return [{ label: '어린이 역량', keys: [...CHILD_SKILLS] }, ...grown];
  return grown;
}
